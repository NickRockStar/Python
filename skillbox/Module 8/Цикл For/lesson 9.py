# Используя цикл for, напишите программу, которая выводит только чётные числа в порядке убывания.
# Нельзя использовать условный оператор.

n = int(input("Сколько секунд считать? "))
even_n = n - n % 2
# чётное число
for i in range(even_n, 0, -2):
    print(i)
