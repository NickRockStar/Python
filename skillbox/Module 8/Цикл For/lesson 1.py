# Задача 1. Таблица кубов
# Паше для проекта по математике нужна таблица кубов (третья степень числа) только чётных чисел от 1 до N.
# Напишите программу, которая выведет ему эту таблицу на экран. Не используйте условные операторы,
# выведите формулу, как мы сделали это на видео.

n = int(input("До какого числа идти: "))
for i in range(1, n // 2 + 1):
    print("Число:", i * 2, "куб числа:", (i * 2) ** 3)